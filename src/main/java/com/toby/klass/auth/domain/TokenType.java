package com.toby.klass.auth.domain;

/**
 * 토큰 종류. JWT 의 {@code typ} 클레임 값이자, 파싱 시 기대 타입으로 넘기는 값이다.
 *
 * <h2>이 enum 이 왜 필요한가</h2>
 * Access 와 Refresh 는 서명 키가 같고 구조도 같다. 구분자가 없으면 유효기간이 훨씬 긴
 * Refresh 토큰을 Access 토큰 자리에 넣어 쓸 수 있다(토큰 타입 혼동 공격).
 * {@code typ} 클레임을 넣고 파싱 시점에 기대값과 대조해 이를 막는다.
 *
 * <p>도메인 패키지에 두는 이유는 아웃바운드 포트 시그니처가 이 타입을 참조하기 때문이다.
 * 포트는 도메인을 import 할 수 있지만 그 반대는 안 된다.
 *
 * <p>Design Ref: §3.4 시각 타입 매핑, §2.3 의존성
 */
public enum TokenType {

    /** 보호된 API 접근용. 만료가 짧다(기본 30분). 권한 클레임을 싣는다. */
    ACCESS,

    /**
     * 재발급 전용. 만료가 길다(기본 14일).
     *
     * <p>권한 클레임을 싣지 않는다 — 재발급 시점에 DB 에서 최신 권한을 다시 읽으므로
     * 권한 변경이 즉시 반영된다.
     */
    REFRESH
}
